<?php

declare(strict_types=1);

namespace HangTuah\GateTrail\Tests\Integration\PostgreSql;

/**
 * DBA-managed provisioning: the committed release `0001` artifacts install the
 * schema and the package migrations do not run.
 *
 * This is inspection evidence for the artifact lane only. Application runtime
 * compatibility on PostgreSQL is not claimed or exercised here.
 */
final class DbaManagedSchemaTest extends PostgreSqlIntegrationTestCase
{
    public function test_artifacts_install_inspect_and_rollback(): void
    {
        $this->artisan('migrate', [
            '--database' => self::CONNECTION,
        ])->assertExitCode(0);

        $this->assertGateTrailTablesExist(false);

        $this->executeArtifact('install');
        $this->assertGateTrailTablesExist(true);
        $this->assertInspectionPasses($this->inspectSchema());

        $this->executeArtifact('rollback');
        $this->assertGateTrailTablesExist(false);
    }

    /**
     * The artifact lane installs `GENERATED BY DEFAULT AS IDENTITY` and the
     * manifest's own primary-key names — the other accepted representation.
     */
    public function test_the_artifact_lane_installs_identity_keys_and_manifest_primary_key_names(): void
    {
        $this->executeArtifact('install');

        $identity = $this->connection()->selectOne(
            <<<'SQL'
                SELECT is_identity, identity_generation
                FROM information_schema.columns
                WHERE table_schema = ?
                  AND table_name = ?
                  AND column_name = 'id'
                SQL,
            [$this->activeSchema(), 'acl_roles'],
        );

        $this->assertSame('YES', $this->rowValue($identity, 'is_identity'));
        $this->assertSame(
            'BY DEFAULT',
            $this->rowValue($identity, 'identity_generation'),
        );

        $primary = $this->connection()->selectOne(
            <<<'SQL'
                SELECT con.conname
                FROM pg_catalog.pg_constraint con
                INNER JOIN pg_catalog.pg_class c ON c.oid = con.conrelid
                INNER JOIN pg_catalog.pg_namespace n
                    ON n.oid = c.relnamespace
                WHERE n.nspname = ?
                  AND c.relname = ?
                  AND con.contype = 'p'
                SQL,
            [$this->activeSchema(), 'acl_roles'],
        );

        $this->assertSame(
            'acl_roles_pk',
            $this->rowValue($primary, 'conname'),
        );
        $this->assertInspectionPasses($this->inspectSchema());
    }

    /**
     * PostgreSQL creates one index per primary-key and unique constraint, so
     * the canonical schema carries 24 indexes: the manifest's 15 explicit ones
     * plus seven primary keys and two unique constraints. None of the nine
     * constraint-backed indexes may be reported as unexpected.
     */
    public function test_constraint_backed_indexes_are_present_and_not_reported(): void
    {
        $this->executeArtifact('install');

        $counts = $this->connection()->selectOne(
            <<<'SQL'
                SELECT
                    COUNT(*) AS total,
                    COUNT(con.conname) AS constraint_backed
                FROM pg_catalog.pg_index ix
                INNER JOIN pg_catalog.pg_class i ON i.oid = ix.indexrelid
                INNER JOIN pg_catalog.pg_class t ON t.oid = ix.indrelid
                INNER JOIN pg_catalog.pg_namespace n
                    ON n.oid = t.relnamespace
                LEFT JOIN pg_catalog.pg_constraint con
                    ON con.conindid = ix.indexrelid
                   AND con.contype IN ('p', 'u')
                WHERE n.nspname = ?
                  AND t.relname LIKE 'acl\_%'
                SQL,
            [$this->activeSchema()],
        );

        $this->assertSame(24, (int) $this->rowValue($counts, 'total'));
        $this->assertSame(
            9,
            (int) $this->rowValue($counts, 'constraint_backed'),
        );

        $inspection = $this->inspectSchema();

        $this->assertNotContains(
            'unexpected_index',
            $this->inspectionCodes($inspection),
        );
        $this->assertInspectionPasses($inspection);
    }

    protected function provisioningMode(): string
    {
        return 'dba';
    }
}
