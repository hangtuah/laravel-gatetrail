    }

    private function recordingReader(
        PostgreSqlCatalogSnapshot $snapshot,
    ): PostgreSqlCatalogReader {
        return new class($snapshot) implements PostgreSqlCatalogReader
        {
            public function __construct(
                private readonly PostgreSqlCatalogSnapshot $snapshot,
            ) {}

            public function read(
                SchemaManifest $manifest,
                SchemaContext $context,
            ): PostgreSqlCatalogSnapshot {
                return $this->snapshot;
            }
        };
    }

    /**
     * Builds the catalog PostgreSQL actually reports after the named
     * provisioning mode installs the canonical schema.
     */
    private function matchingSnapshot(
        string $mode,
        string $prefix = '',
        string $schema = 'public',
    ): PostgreSqlCatalogSnapshot {
        $tables = [];
        $columns = [];
        $indexes = [];
        $constraints = [];
        $identities = [];
        $context = $this->context($prefix === '' ? null : $prefix);

        foreach ($this->manifest()->tables() as $table) {
            $physicalTable = $context->tableName($table->key);
            $tables[] = $physicalTable;

            foreach ($table->columns as $column) {
                $columns[] = $this->canonicalColumn($physicalTable, $column);

                if (! $column->generated) {
                    continue;
                }

                $identities[] = new PostgreSqlIdentityMetadata(
                    table: $physicalTable,
                    column: $column->name,
                    generation: $mode === self::DBA
                        ? PostgreSqlIdentityGeneration::ByDefault
                        : PostgreSqlIdentityGeneration::SequenceDefault,
                    sequence: $mode === self::DBA
                        ? null
                        : $physicalTable.'_'.$column->name.'_seq',
                );
            }

            foreach ($table->indexes as $index) {
                $indexes[] = new PostgreSqlIndexMetadata(
                    table: $physicalTable,
                    name: $index->name,
                    columns: $index->columns,
                    unique: false,
                    primary: false,
                    valid: true,
                    live: true,
                    complete: true,
                );
            }

            foreach ($table->constraints as $constraint) {
                $name = $this->physicalConstraintName(
                    $constraint,
                    $physicalTable,
                    $mode,
                );
                $constraints[] = $this->canonicalConstraint(
                    $physicalTable,
                    $name,
                    $constraint,
                    $context,
                    $schema,
                );

                if (! in_array($constraint->type, [
                    ConstraintType::Primary,
                    ConstraintType::Unique,
                ], true)) {
                    continue;
                }

                $indexes[] = new PostgreSqlIndexMetadata(
                    table: $physicalTable,
                    name: $name,
                    columns: $constraint->columns,
                    unique: true,
                    primary: $constraint->type === ConstraintType::Primary,
                    valid: true,
                    live: true,
                    complete: true,
                    constraint: $name,
                );
            }
        }

        return new PostgreSqlCatalogSnapshot(
            schema: $schema,
            tables: $tables,
            columns: $columns,
            indexes: $indexes,
            constraints: $constraints,
            identities: $identities,
        );
    }

    /**
     * Laravel's PostgreSQL grammar cannot name a primary key, so PostgreSQL
     * assigns `<table>_pkey` for package-managed provisioning.
     */
    private function physicalConstraintName(
        ConstraintDefinition $constraint,
        string $physicalTable,
        string $mode,
    ): string {
        return $constraint->type === ConstraintType::Primary
            && $mode === self::PACKAGE
                ? $physicalTable.'_pkey'
                : $constraint->name;
    }

    private function canonicalColumn(
        string $table,
        ColumnDefinition $column,
    ): PostgreSqlColumnMetadata {
        [$dataType, $precision] = match ($column->type) {
            ColumnType::BigInteger => ['bigint', null],
            ColumnType::DateTime => ['timestamp without time zone', 0],
            ColumnType::FixedString => ['character', null],
            ColumnType::String => ['character varying', null],
            ColumnType::Text => ['text', null],
        };
        $character = in_array(
            $column->type,
            [ColumnType::FixedString, ColumnType::String],
            true,
        );

        return new PostgreSqlColumnMetadata(
            table: $table,
            name: $column->name,
            dataType: $dataType,
            nullable: $column->nullable,
            characterLength: $character ? $column->length : null,
            datetimePrecision: $precision,
            collation: $column->exactComparison ? 'C' : null,
            default: null,
        );
    }

    private function canonicalConstraint(
        string $table,
        string $name,
        ConstraintDefinition $constraint,
        SchemaContext $context,
        string $schema,
    ): PostgreSqlConstraintMetadata {
        $foreign = $constraint->type === ConstraintType::Foreign;

        return new PostgreSqlConstraintMetadata(
            table: $table,
            name: $name,
            type: match ($constraint->type) {
                ConstraintType::Primary => 'p',
                ConstraintType::Unique => 'u',
                ConstraintType::Foreign => 'f',
                ConstraintType::Check => 'c',
            },
            columns: $constraint->columns,
            validated: true,
            referencedSchema: $foreign ? $schema : null,
            referencedTable: $constraint->referencedTable === null
                ? null
                : $context->tableName($constraint->referencedTable),
            referencedColumns: $constraint->referencedColumns,
            deleteRule: $foreign ? 'RESTRICT' : null,
            updateRule: $foreign ? 'RESTRICT' : null,
            checkExpression: $constraint->type === ConstraintType::Check
                ? $constraint->expression
                : null,
        );
    }

