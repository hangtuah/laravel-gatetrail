/**
 * Drift classification for the strict PostgreSQL inspector.
 *
 * Both provisioning modes are exercised as separate baselines, because
 * PostgreSQL represents the same canonical contract differently depending on
 * which one installed it: the release `0001` artifacts name every primary key
 * and use `GENERATED BY DEFAULT AS IDENTITY`, while Laravel's PostgreSQL
 * grammar leaves PostgreSQL to name the primary key `<table>_pkey` and emits
 * `bigserial`. Both must inspect clean; everything else must be reported.
 */
final class PostgreSqlSchemaInspectorTest extends TestCase
{
    private const DBA = 'dba';

    private const PACKAGE = 'package';

    /**
     * @return array<string, array{string}>
     */
    public static function provisioningModes(): array
    {
        return [
            'DBA-managed release 0001 artifacts' => [self::DBA],
            'package-managed Laravel migrations' => [self::PACKAGE],
        ];
    }

