    public function test_index_drift_covers_absence_order_uniqueness_and_state(): void
    {
        $snapshot = $this->matchingSnapshot(self::DBA);
        $indexes = [];

        foreach ($snapshot->indexes as $index) {
            if ($index->name === 'acl_ra_subject_ix') {
                continue;
            }

            if ($index->name === 'acl_ra_scope_ix') {
                $indexes[] = $this->index(
                    $index,
                    columns: array_reverse($index->columns),
                );

                continue;
            }

            if ($index->name === 'acl_ra_role_ix') {
                $indexes[] = $this->index($index, unique: true);

                continue;
            }

            if ($index->name === 'acl_audit_created_ix') {
                $indexes[] = $this->index($index, valid: false);

                continue;
            }

            $indexes[] = $index;
        }

        $indexes[] = new PostgreSqlIndexMetadata(
            table: 'acl_roles',
            name: 'acl_roles_legacy_ix',
            columns: ['name'],
            unique: false,
            primary: false,
            valid: true,
            live: true,
            complete: true,
        );

        $issues = $this->inspect(
            $this->replaceIndexes($snapshot, $indexes),
        )->issues;

        $this->assertSame(
            'missing_index',
            $this->codeFor($issues, 'acl_role_assignments.acl_ra_subject_ix'),
        );
        $this->assertSame(
            'index_definition_mismatch',
            $this->codeFor($issues, 'acl_role_assignments.acl_ra_scope_ix'),
        );
        $this->assertSame(
            'index_definition_mismatch',
            $this->codeFor($issues, 'acl_role_assignments.acl_ra_role_ix'),
        );
        $this->assertSame(
            'index_state_mismatch',
            $this->codeFor($issues, 'acl_access_audits.acl_audit_created_ix'),
        );
        $this->assertSame(
            'unexpected_index',
            $this->codeFor($issues, 'acl_roles.acl_roles_legacy_ix'),
        );
    }

