    /**
     * @return array<string, array{bool, bool, bool}>
     */
    public static function deferrabilityStates(): array
    {
        return [
            'NOT DEFERRABLE' => [false, false, true],
            'DEFERRABLE INITIALLY IMMEDIATE' => [true, false, false],
            'DEFERRABLE INITIALLY DEFERRED' => [true, true, false],
        ];
    }

    /**
     * PostgreSQL can postpone a `NO ACTION` check to commit time, which
     * `RESTRICT` cannot be postponed the same way, so the two actions are only
     * interchangeable while the constraint is `NOT DEFERRABLE`. Both restrictive
     * actions are exercised here so the assertion isolates deferrability.
     */
    #[DataProvider('deferrabilityStates')]
    public function test_only_a_not_deferrable_foreign_key_is_canonical(
        bool $deferrable,
        bool $deferred,
        bool $accepted,
    ): void {
        foreach (['RESTRICT', 'NO ACTION'] as $action) {
            $snapshot = $this->matchingSnapshot(self::DBA);
            $constraints = array_map(
                fn (PostgreSqlConstraintMetadata $constraint): PostgreSqlConstraintMetadata => (
                    $constraint->type === 'f'
                ) ? $this->constraint(
                    $constraint,
                    deferrable: $deferrable,
                    deferred: $deferred,
                    deleteRule: $action,
                    updateRule: $action,
                ) : $constraint,
                $snapshot->constraints,
            );

            $inspection = $this->inspect(
                $this->replaceConstraints($snapshot, $constraints),
            );

            if ($accepted) {
                $this->assertSame(
                    [],
                    $this->codes($inspection),
                    sprintf('NOT DEFERRABLE with ON DELETE %s', $action),
                );

                continue;
            }

            $this->assertSame(
                'constraint_state_mismatch',
                $this->codeFor(
                    $inspection->issues,
                    'acl_role_assignments.acl_ra_role_fk',
                ),
                sprintf('deferrable with ON DELETE %s', $action),
            );
            $this->assertFalse($inspection->passes());
            $this->assertStringContainsString(
                $deferred ? 'INITIALLY DEFERRED' : 'INITIALLY IMMEDIATE',
                $this->messageFor(
                    $inspection->issues,
                    'acl_role_assignments.acl_ra_role_fk',
                ),
            );
        }
    }

    /**
     * @return array<string, array{string, bool, bool, ?string}>
     */
    public static function constraintDeferrability(): array
    {
        $cases = [];

        foreach ([
            'primary key' => 'acl_audit_pk',
            'unique' => 'acl_role_name_guard_uq',
            'foreign key' => 'acl_ra_role_fk',
        ] as $kind => $constraint) {
            $cases[$kind.', NOT DEFERRABLE'] = [
                $constraint, false, false, null,
            ];
            $cases[$kind.', DEFERRABLE INITIALLY IMMEDIATE'] = [
                $constraint, true, false, 'INITIALLY IMMEDIATE',
            ];
            $cases[$kind.', DEFERRABLE INITIALLY DEFERRED'] = [
                $constraint, true, true, 'INITIALLY DEFERRED',
            ];
        }

        return $cases;
    }

    /**
     * The rule is one rule, applied to every manifest constraint type that
     * PostgreSQL can make deferrable.
     */
    #[DataProvider('constraintDeferrability')]
    public function test_every_constraint_type_must_be_not_deferrable(
        string $constraintName,
        bool $deferrable,
        bool $deferred,
        ?string $expectedState,
    ): void {
        $snapshot = $this->matchingSnapshot(self::DBA);
        $object = null;
        $constraints = [];

        foreach ($snapshot->constraints as $constraint) {
            if ($constraint->name !== $constraintName) {
                $constraints[] = $constraint;

                continue;
            }

            $object = $constraint->table.'.'.$constraint->name;
            $constraints[] = $this->constraint(
                $constraint,
                deferrable: $deferrable,
                deferred: $deferred,
            );
        }

        $this->assertNotNull($object, $constraintName);

        $inspection = $this->inspect(
            $this->replaceConstraints($snapshot, $constraints),
        );

        if ($expectedState === null) {
            $this->assertSame([], $this->codes($inspection));

            return;
        }

        $this->assertSame(
            ['constraint_state_mismatch'],
            $this->codes($inspection),
            'A deferrable constraint must raise exactly one issue.',
        );
