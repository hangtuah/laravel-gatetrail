        string|false|null $referencedSchema = false,
        string|false|null $referencedTable = false,
        ?array $referencedColumns = null,
        string|false|null $deleteRule = false,
        string|false|null $updateRule = false,
        string|false|null $checkExpression = false,
    ): PostgreSqlConstraintMetadata {
        return new PostgreSqlConstraintMetadata(
            table: $constraint->table,
            name: $name ?? $constraint->name,
            type: $type ?? $constraint->type,
            columns: $columns ?? $constraint->columns,
            validated: $validated ?? $constraint->validated,
            deferrable: $deferrable ?? $constraint->deferrable,
            deferred: $deferred ?? $constraint->deferred,
            referencedSchema: $referencedSchema === false
                ? $constraint->referencedSchema
                : $referencedSchema,
            referencedTable: $referencedTable === false
                ? $constraint->referencedTable
                : $referencedTable,
            referencedColumns: $referencedColumns
                ?? $constraint->referencedColumns,
            deleteRule: $deleteRule === false
                ? $constraint->deleteRule
                : $deleteRule,
            updateRule: $updateRule === false
                ? $constraint->updateRule
                : $updateRule,
            checkExpression: $checkExpression === false
                ? $constraint->checkExpression
                : $checkExpression,
        );
    }

    /**
     * @return list<SchemaIssue>
     */
    private function issuesFor(
        PostgreSqlCatalogSnapshot $snapshot,
        string $table,
    ): array {
        return array_values(array_filter(
            $this->inspect($snapshot)->issues,
            static fn ($issue): bool => str_starts_with(
                $issue->object,
                $table.'.',
            ),
        ));
    }

    /**
     * @param  list<SchemaIssue>  $issues
     */
    private function codeFor(array $issues, string $object): ?string
    {
        foreach ($issues as $issue) {
            if ($issue->object === $object) {
                return $issue->code;
            }
        }

        return null;
    }

    /**
     * @param  list<SchemaIssue>  $issues
     */
    private function messageFor(array $issues, string $object): string
    {
        foreach ($issues as $issue) {
            if ($issue->object === $object) {
                return $issue->message;
            }
        }

        return '';
    }

    /**
     * @return list<string>
     */
    private function codes(SchemaInspection $inspection): array
    {
        return array_map(
            static fn ($issue): string => $issue->code,
            $inspection->issues,
        );
    }

    private function context(
        ?string $prefix = null,
        ?string $schema = null,
    ): SchemaContext {
        $config = require dirname(__DIR__, 2).'/config/gatetrail.php';
        $config['database']['prefix'] = $prefix;
        $config['database']['schema'] = $schema;

        return new SchemaContext(
            $config,
            new IdentifierValidator,
            $this->manifest(),
        );
    }

    private function manifest(): SchemaManifest
    {
        return $this->app->make(SchemaManifest::class);
    }
