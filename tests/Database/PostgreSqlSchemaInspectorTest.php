            table: 'acl_roles',
            name: 'legacy_flag',
            dataType: 'boolean',
            nullable: true,
            characterLength: null,
            datetimePrecision: null,
            collation: null,
            default: null,
        );

        $issues = $this->issuesFor(
            $this->replaceColumns($snapshot, $columns),
            'acl_roles',
        );

