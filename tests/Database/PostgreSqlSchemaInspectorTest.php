    private function inspect(
        PostgreSqlCatalogSnapshot $snapshot,
        ?string $prefix = null,
        ?string $schema = null,
    ): SchemaInspection {
        return (new PostgreSqlSchemaInspector(
            $this->recordingReader($snapshot),
