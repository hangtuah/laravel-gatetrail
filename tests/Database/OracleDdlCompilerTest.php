<?php

declare(strict_types=1);

namespace HangTuah\GateTrail\Tests\Database;

use HangTuah\GateTrail\Database\Schema\Ddl\DdlCompiler;
use HangTuah\GateTrail\Database\Schema\Ddl\DdlCompilerFactory;
use HangTuah\GateTrail\Database\Schema\Manifest\SchemaManifest;
use HangTuah\GateTrail\Database\Schema\SchemaContext;
use HangTuah\GateTrail\Exceptions\InvalidDatabaseIdentifier;
use HangTuah\GateTrail\Tests\TestCase;
use InvalidArgumentException;

final class OracleDdlCompilerTest extends TestCase
{
    public function test_identity_install_follows_manifest_dependency_order(): void
    {
        $this->useStrategy('identity');

        $statements = $this->compiler()->compileInstall(
            $this->manifest(),
            $this->context(),
        );
        $ddl = implode("\n", $statements);

        $this->assertCount(22, $statements);
        $this->assertStringContainsString(
            'id NUMBER(19,0) GENERATED BY DEFAULT ON NULL AS IDENTITY '
            .'(START WITH 1 INCREMENT BY 1 NOCYCLE CACHE 20) NOT NULL',
            $statements[0],
        );
        $this->assertSame(6, substr_count($ddl, ' AS IDENTITY'));
        $this->assertStringNotContainsString('CREATE SEQUENCE', $ddl);
        $this->assertStringNotContainsString('CREATE TRIGGER', $ddl);
        $this->assertStringNotContainsString(
            'assignment_kind CHAR',
            $statements[2],
        );
        $this->assertLessThan(
            strpos($ddl, 'CREATE TABLE acl_role_assignments'),
            strpos($ddl, 'CREATE TABLE acl_roles'),
        );
    }

    public function test_sequence_trigger_install_creates_six_explicit_key_pairs(): void
    {
        $statements = $this->compiler()->compileInstall(
            $this->manifest(),
            $this->context(),
        );
        $ddl = implode("\n", $statements);

        $this->assertCount(34, $statements);
        $this->assertSame(6, substr_count($ddl, 'CREATE SEQUENCE'));
        $this->assertSame(6, substr_count($ddl, 'CREATE TRIGGER'));
        $this->assertStringContainsString(
            'CREATE SEQUENCE acl_roles_seq START WITH 1 INCREMENT BY 1 NOCYCLE CACHE 20;',
            $ddl,
        );
        $this->assertStringContainsString(
            "IF :NEW.id IS NULL THEN\n"
            .'        :NEW.id := acl_roles_seq.NEXTVAL;',
            $ddl,
        );
        $this->assertStringNotContainsString('acl_assignment_locks_seq', $ddl);
        $this->assertStringNotContainsString(' AS IDENTITY', $ddl);
    }

    public function test_oracle_types_constraints_and_indexes_are_native(): void
    {
        $statements = $this->compiler()->compileInstall(
            $this->manifest(),
            $this->context(),
        );
        $ddl = implode("\n", $statements);

        $this->assertStringContainsString('name VARCHAR2(191 CHAR) NOT NULL', $ddl);
        $this->assertStringContainsString('description CLOB NULL', $ddl);
        $this->assertStringContainsString('created_at TIMESTAMP(6) NOT NULL', $ddl);
        $this->assertStringContainsString(
            'CONSTRAINT acl_roles_pk PRIMARY KEY (id)',
            $ddl,
        );
        $this->assertStringContainsString(
            'CONSTRAINT acl_ra_role_fk FOREIGN KEY (role_id) REFERENCES acl_roles (id)',
            $ddl,
        );
        $this->assertStringContainsString(
            'CREATE INDEX acl_ra_subject_ix ON acl_role_assignments',
            $ddl,
        );
        $this->assertStringNotContainsString('ON UPDATE', $ddl);
        $this->assertStringNotContainsString('CASCADE', $ddl);
    }

    public function test_rollback_drops_triggers_tables_and_sequences_in_dependency_order(): void
    {
        $statements = $this->compiler()->compileRollback(
            $this->manifest(),
            $this->context(),
        );

        $this->assertCount(19, $statements);
        $this->assertSame(
            'DROP TRIGGER acl_audit_trg;',
            $statements[0],
        );
        $this->assertSame(
            'DROP TABLE acl_access_audits;',
            $statements[6],
        );
        $this->assertSame(
            'DROP TABLE acl_roles;',
            $statements[12],
        );
        $this->assertSame(
            'DROP SEQUENCE acl_audit_seq;',
            $statements[13],
        );
        $this->assertSame(
            'DROP SEQUENCE acl_roles_seq;',
            $statements[18],
        );
    }

    public function test_identity_rollback_drops_only_reverse_ordered_tables(): void
    {
        $this->useStrategy('identity');

        $statements = $this->compiler()->compileRollback(
            $this->manifest(),
            $this->context(),
        );

        $this->assertCount(7, $statements);
        $this->assertSame(
            'DROP TABLE acl_access_audits;',
            $statements[0],
        );
        $this->assertSame('DROP TABLE acl_roles;', $statements[6]);
    }

    public function test_schema_prefix_and_custom_key_objects_are_qualified(): void
    {
        $this->app['config']->set('gatetrail.database.schema', 'security');
        $this->app['config']->set('gatetrail.database.prefix', 'app_');
        $this->app['config']->set(
            'gatetrail.oracle.sequences.roles',
            'security_roles_seq',
        );
        $this->app['config']->set(
            'gatetrail.oracle.triggers.roles',
            'security_roles_trg',
        );

        $ddl = implode("\n", $this->compiler()->compileInstall(
            $this->manifest(),
            $this->context(),
        ));

        $this->assertStringContainsString(
            'CREATE TABLE security.app_acl_roles',
            $ddl,
        );
        $this->assertStringContainsString(
            'CREATE SEQUENCE security.security_roles_seq',
            $ddl,
        );
        $this->assertStringContainsString(
            'CREATE TRIGGER security.security_roles_trg',
            $ddl,
        );
        $this->assertStringContainsString(
            'ON security.app_acl_roles',
            $ddl,
        );
    }

    public function test_invalid_strategy_fails_before_any_ddl_is_returned(): void
    {
        $this->useStrategy('automatic');

        $this->expectException(InvalidArgumentException::class);
        $this->expectExceptionMessage(
            'GateTrail oracle.generated_keys must be [identity] or [sequence_trigger].',
        );

        $this->compiler()->compileInstall(
            $this->manifest(),
            $this->context(),
        );
    }

    public function test_invalid_sequence_name_fails_before_any_ddl_is_returned(): void
    {
        $this->app['config']->set(
            'gatetrail.oracle.sequences.roles',
            str_repeat('a', 31),
        );

        $this->expectException(InvalidDatabaseIdentifier::class);
        $this->expectExceptionMessage('Oracle sequence [roles]');

        $this->compiler()->compileInstall(
            $this->manifest(),
            $this->context(),
        );
    }

    public function test_factory_resolves_the_oracle_compiler(): void
    {
        $this->assertInstanceOf(
            DdlCompiler::class,
            $this->app->make(DdlCompilerFactory::class)
                ->forDriver('oracle'),
        );
    }

    private function useStrategy(string $strategy): void
    {
        $this->app['config']->set(
            'gatetrail.oracle.generated_keys',
            $strategy,
        );
    }

    private function compiler(): DdlCompiler
    {
        return $this->app->make(DdlCompilerFactory::class)
            ->forDriver('oracle');
    }

    private function manifest(): SchemaManifest
    {
        return $this->app->make(SchemaManifest::class);
    }

    private function context(): SchemaContext
    {
        return $this->app->make(SchemaContext::class);
    }
}
