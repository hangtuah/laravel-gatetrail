<?php

declare(strict_types=1);

namespace HangTuah\GateTrail\Database\Schema\Ddl\Oracle;

use HangTuah\GateTrail\Database\Schema\Ddl\DdlCompiler;
use HangTuah\GateTrail\Database\Schema\Manifest\ColumnDefinition;
use HangTuah\GateTrail\Database\Schema\Manifest\ColumnType;
use HangTuah\GateTrail\Database\Schema\Manifest\ConstraintDefinition;
use HangTuah\GateTrail\Database\Schema\Manifest\ConstraintType;
use HangTuah\GateTrail\Database\Schema\Manifest\IndexDefinition;
use HangTuah\GateTrail\Database\Schema\Manifest\SchemaManifest;
use HangTuah\GateTrail\Database\Schema\Manifest\TableDefinition;
use HangTuah\GateTrail\Database\Schema\SchemaContext;
use LogicException;

final class OracleDdlCompiler implements DdlCompiler
{
    public function compileInstall(
        SchemaManifest $manifest,
        SchemaContext $context,
    ): array {
        $context->validateAll();
        $options = $context->oracleOptions();
        $generatedTables = $this->generatedTables($manifest);
        $options->validateFor(array_keys($generatedTables));
        $statements = [];

        foreach ($manifest->tables() as $table) {
            $statements[] = $this->compileTable($table, $context, $options);

            foreach ($table->indexes as $index) {
                $statements[] = $this->compileIndex($table, $index, $context);
            }

            if (
                $options->generatedKeys === OracleGeneratedKeyStrategy::SequenceTrigger
                && isset($generatedTables[$table->key])
            ) {
                $statements[] = $this->compileSequence(
                    $table->key,
                    $context,
                    $options,
                );
                $statements[] = $this->compileTrigger(
                    $table,
                    $generatedTables[$table->key],
                    $context,
                    $options,
                );
            }
        }

        return $statements;
    }

    public function compileRollback(
        SchemaManifest $manifest,
        SchemaContext $context,
    ): array {
        $context->validateAll();
        $options = $context->oracleOptions();
        $generatedTables = $this->generatedTables($manifest);
        $options->validateFor(array_keys($generatedTables));
        $statements = [];
        $generatedKeys = array_keys($generatedTables);

        if ($options->generatedKeys === OracleGeneratedKeyStrategy::SequenceTrigger) {
            foreach (array_reverse($generatedKeys) as $tableKey) {
                $statements[] = sprintf(
                    'DROP TRIGGER %s;',
                    $this->qualifiedObject(
                        $options->trigger($tableKey),
                        $context,
                    ),
                );
            }
        }

        foreach ($manifest->rollbackOrder() as $tableKey) {
            $statements[] = sprintf(
                'DROP TABLE %s;',
                $context->table($tableKey),
            );
        }

        if ($options->generatedKeys === OracleGeneratedKeyStrategy::SequenceTrigger) {
            foreach (array_reverse($generatedKeys) as $tableKey) {
                $statements[] = sprintf(
                    'DROP SEQUENCE %s;',
                    $this->qualifiedObject(
                        $options->sequence($tableKey),
                        $context,
                    ),
                );
            }
        }

        return $statements;
    }

    private function compileTable(
        TableDefinition $table,
        SchemaContext $context,
        OracleSchemaOptions $options,
    ): string {
        $definitions = [
            ...array_map(
                fn (ColumnDefinition $column): string => $this->compileColumn(
                    $column,
                    $options,
                ),
                $table->columns,
            ),
            ...array_map(
                fn (ConstraintDefinition $constraint): string => $this->compileConstraint(
                    $constraint,
                    $context,
                ),
                $table->constraints,
            ),
        ];

        return sprintf(
            "CREATE TABLE %s (\n    %s\n);",
            $context->table($table->key),
            implode(",\n    ", $definitions),
        );
    }

    private function compileColumn(
        ColumnDefinition $column,
        OracleSchemaOptions $options,
    ): string {
        $definition = [
            $column->name,
            $this->columnType($column),
        ];

        if (
            $column->generated
            && $options->generatedKeys === OracleGeneratedKeyStrategy::Identity
        ) {
            $definition[] = 'GENERATED BY DEFAULT ON NULL AS IDENTITY';
            $definition[] = '(START WITH 1 INCREMENT BY 1 NOCYCLE CACHE 20)';
        }

        $definition[] = $column->nullable ? 'NULL' : 'NOT NULL';

        return implode(' ', $definition);
    }

    private function columnType(ColumnDefinition $column): string
    {
        return match ($column->type) {
            ColumnType::BigInteger => 'NUMBER(19,0)',
            ColumnType::DateTime => 'TIMESTAMP(6)',
            ColumnType::FixedString => sprintf(
                'CHAR(%d CHAR)',
                $column->length ?? 1,
            ),
            ColumnType::String => sprintf(
                'VARCHAR2(%d CHAR)',
                $column->length ?? 191,
            ),
            ColumnType::Text => 'CLOB',
        };
    }

    private function compileConstraint(
        ConstraintDefinition $constraint,
        SchemaContext $context,
    ): string {
        return match ($constraint->type) {
            ConstraintType::Primary => sprintf(
                'CONSTRAINT %s PRIMARY KEY (%s)',
                $constraint->name,
                $this->columnList($constraint->columns),
            ),
            ConstraintType::Unique => sprintf(
                'CONSTRAINT %s UNIQUE (%s)',
                $constraint->name,
                $this->columnList($constraint->columns),
            ),
            ConstraintType::Foreign => $this->compileForeign(
                $constraint,
                $context,
            ),
            ConstraintType::Check => sprintf(
                'CONSTRAINT %s CHECK (%s)',
                $constraint->name,
                $constraint->expression
                    ?? throw new LogicException('A check constraint requires an expression.'),
            ),
        };
    }

    private function compileForeign(
        ConstraintDefinition $constraint,
        SchemaContext $context,
    ): string {
        $referencedTable = $constraint->referencedTable
            ?? throw new LogicException('A foreign key requires a referenced table.');

        return sprintf(
            'CONSTRAINT %s FOREIGN KEY (%s) REFERENCES %s (%s)',
            $constraint->name,
            $this->columnList($constraint->columns),
            $context->table($referencedTable),
            $this->columnList($constraint->referencedColumns),
        );
    }

    private function compileIndex(
        TableDefinition $table,
        IndexDefinition $index,
        SchemaContext $context,
    ): string {
        return sprintf(
            'CREATE INDEX %s ON %s (%s);',
            $this->qualifiedObject($index->name, $context),
            $context->table($table->key),
            $this->columnList($index->columns),
        );
    }

    private function compileSequence(
        string $tableKey,
        SchemaContext $context,
        OracleSchemaOptions $options,
    ): string {
        return sprintf(
            'CREATE SEQUENCE %s START WITH 1 INCREMENT BY 1 NOCYCLE CACHE 20;',
            $this->qualifiedObject($options->sequence($tableKey), $context),
        );
    }

    private function compileTrigger(
        TableDefinition $table,
        ColumnDefinition $column,
        SchemaContext $context,
        OracleSchemaOptions $options,
    ): string {
        $sequence = $this->qualifiedObject(
            $options->sequence($table->key),
            $context,
        );

        return sprintf(
            "CREATE TRIGGER %s\n"
            ."BEFORE INSERT ON %s\n"
            ."FOR EACH ROW\n"
            ."BEGIN\n"
            ."    IF :NEW.%s IS NULL THEN\n"
            ."        :NEW.%s := %s.NEXTVAL;\n"
            ."    END IF;\n"
            ."END;\n/",
            $this->qualifiedObject($options->trigger($table->key), $context),
            $context->table($table->key),
            $column->name,
            $column->name,
            $sequence,
        );
    }

    /**
     * @return array<string, ColumnDefinition>
     */
    private function generatedTables(SchemaManifest $manifest): array
    {
        $generatedTables = [];

        foreach ($manifest->tables() as $table) {
            $generated = array_values(array_filter(
                $table->columns,
                static fn (ColumnDefinition $column): bool => $column->generated,
            ));

            if (count($generated) > 1) {
                throw new LogicException(
                    sprintf(
                        'Oracle DDL supports one generated column per table; [%s] has more than one.',
                        $table->key,
                    ),
                );
            }

            if ($generated !== []) {
                $generatedTables[$table->key] = $generated[0];
            }
        }

        return $generatedTables;
    }

    /**
     * @param  list<string>  $columns
     */
    private function columnList(array $columns): string
    {
        return implode(', ', $columns);
    }

    private function qualifiedObject(
        string $identifier,
        SchemaContext $context,
    ): string {
        $schema = $context->schemaName();

        return $schema === null ? $identifier : $schema.'.'.$identifier;
    }
}
