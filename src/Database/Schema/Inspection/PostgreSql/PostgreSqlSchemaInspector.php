<?php

declare(strict_types=1);

namespace HangTuah\GateTrail\Database\Schema\Inspection\PostgreSql;

use HangTuah\GateTrail\Database\Schema\Inspection\InspectionSeverity;
use HangTuah\GateTrail\Database\Schema\Inspection\SchemaInspection;
use HangTuah\GateTrail\Database\Schema\Inspection\SchemaInspector;
use HangTuah\GateTrail\Database\Schema\Inspection\SchemaIssue;
use HangTuah\GateTrail\Database\Schema\Manifest\ColumnDefinition;
use HangTuah\GateTrail\Database\Schema\Manifest\ColumnType;
use HangTuah\GateTrail\Database\Schema\Manifest\ConstraintDefinition;
use HangTuah\GateTrail\Database\Schema\Manifest\ConstraintType;
use HangTuah\GateTrail\Database\Schema\Manifest\IndexDefinition;
use HangTuah\GateTrail\Database\Schema\Manifest\SchemaManifest;
use HangTuah\GateTrail\Database\Schema\Manifest\TableDefinition;
use HangTuah\GateTrail\Database\Schema\SchemaContext;

/**
 * Compares an installed PostgreSQL schema with the canonical manifest and
 * reports the differences. It never repairs, creates, alters, drops or locks
 * anything: every statement behind it is a catalog read.
 *
 * # Normalization, and its limits
 *
 * Two provisioning modes install this schema, and PostgreSQL represents parts
 * of the same canonical contract differently depending on which one ran. The
 * inspector accepts both representations only where they are semantically
 * identical, and reports everything else:
 *
 * - **`RESTRICT` and `NO ACTION`** are both accepted for `ON DELETE` and
 *   `ON UPDATE`, but only while the constraint is `NOT DEFERRABLE`. Neither
 *   permits a referencing row to be orphaned; they differ in when the check
 *   fires. That difference stops being cosmetic once the constraint is
 *   deferrable, because PostgreSQL can postpone a `NO ACTION` check to commit
 *   time while `RESTRICT` cannot be postponed the same way — so a deferrable
 *   foreign key is drift regardless of its action, reported as
 *   `constraint_state_mismatch`. `CASCADE`, `SET NULL` and `SET DEFAULT` are
 *   drift on their own, because each destroys assignment history the package
 *   promises to keep.
 * - **A foreign key's identity includes the schema it references.** Two schemas
 *   can each hold a table of the canonical name, so the referenced namespace,
 *   table and ordered columns must all match. The expected namespace is the
 *   schema actually being inspected — the configured one when supplied, and the
 *   resolved `current_schema()` otherwise — never a hardcoded `public`.
 * - **Primary-key names.** The release `0001` artifacts name every primary key
 *   from the manifest. Laravel's PostgreSQL grammar cannot name one — it emits
 *   `bigserial ... primary key` and `add primary key (...)`, so PostgreSQL
 *   assigns its own `<table>_pkey`. Both names are therefore accepted for a
 *   primary key, and the constraint's columns are compared either way. No
 *   other constraint type gets this latitude: unique, foreign-key and check
 *   constraints are explicitly named by both modes and must match exactly.
 * - **Generated keys.** `GENERATED BY DEFAULT AS IDENTITY` (the artifacts) and
 *   a `nextval(...)` default (Laravel's `bigserial`) are both accepted, because
 *   both auto-assign an identifier and both still accept an explicitly supplied
 *   one. `GENERATED ALWAYS AS IDENTITY` is drift: it rejects an explicit
 *   identifier that GateTrail's own insert paths supply.
 * - **Constraint-backed indexes.** PostgreSQL creates one index per primary-key
 *   and unique constraint. Those are not counted against the manifest's 15
 *   explicit indexes and are not reported as unexpected, provided they back a
 *   constraint the manifest declares.
 *
 * # Unexpected indexes, and why severity differs
 *
 * Every index outside the manifest is reported, but not every one fails
 * conformance. Section 3.8 of the package specification permits an organization
 * to add performance indexes, so an extra non-unique index is reported as a
 * warning: visible to whoever reads the inspection, not a conformance failure.
 * An extra **unique** index, or one backing a constraint the manifest does not
 * declare, is an error on the same reasoning the specification applies to an
 * unexpected column — it can reject an insert GateTrail expects to succeed, so
 * it changes the data contract rather than just the query plan.
 * - **`timestamp without time zone`** is compared with its declared precision,
 *   so the canonical second-precision column is distinguished from a
 *   sub-second one.
 * - **Check expressions** are compared after PostgreSQL's own rewrite is
 *   normalized: case, whitespace and redundant outer parentheses are removed
 *   from both sides before comparison.
 * - **Collation.** A column the manifest marks for exact comparison must
 *   declare the deterministic `C` collation explicitly. Inheriting a database
 *   default that happens to be deterministic is not accepted, because the
 *   default can be changed underneath the package.
 *
 * # Fail-closed
 *
 * Catalog metadata that cannot be compared is reported rather than assumed
 * correct: an expression or partial index, an index key with no resolvable
 * column, an unrecognized referential action, and a check constraint whose
 * definition is not in PostgreSQL's `CHECK (...)` form all raise an issue.
 *
 * @internal
 */
final readonly class PostgreSqlSchemaInspector implements SchemaInspector
{
    public function __construct(
        private PostgreSqlCatalogReader $catalog,
    ) {}

    public function inspect(
        SchemaManifest $manifest,
        SchemaContext $context,
    ): SchemaInspection {
        $snapshot = $this->catalog->read($manifest, $context);
        $issues = [];

        foreach ($manifest->tables() as $table) {
            $physicalTable = $context->tableName($table->key);

            if (! $snapshot->hasTable($physicalTable)) {
                $issues[] = new SchemaIssue(
                    code: 'missing_table',
                    object: $physicalTable,
                    message: sprintf(
                        'Required PostgreSQL table [%s] is absent.',
                        $physicalTable,
                    ),
                );

                continue;
            }

            $issues = [
                ...$issues,
                ...$this->inspectColumns($table, $physicalTable, $snapshot),
                ...$this->inspectIndexes($table, $physicalTable, $snapshot),
                ...$this->inspectConstraints(
                    $table,
                    $physicalTable,
                    $snapshot,
                    $context,
                ),
                ...$this->inspectGeneratedKeys(
                    $table,
                    $physicalTable,
                    $snapshot,
                ),
            ];
        }

        return new SchemaInspection($issues);
    }

    /**
     * @return list<SchemaIssue>
     */
    private function inspectColumns(
        TableDefinition $table,
        string $physicalTable,
        PostgreSqlCatalogSnapshot $snapshot,
    ): array {
        $issues = [];

        foreach ($table->columns as $expected) {
            $actual = $snapshot->column($physicalTable, $expected->name);
            $object = $physicalTable.'.'.$expected->name;

            if ($actual === null) {
                $issues[] = new SchemaIssue(
                    code: 'missing_column',
                    object: $object,
                    message: sprintf('Required column [%s] is absent.', $object),
                );

                continue;
            }

            $issues = [
                ...$issues,
                ...$this->inspectColumn($expected, $actual, $object),
            ];
        }

        foreach ($snapshot->columns as $actual) {
            if (
                $actual->table === $physicalTable
                && ! in_array($actual->name, $table->columnNames(), true)
            ) {
                $issues[] = new SchemaIssue(
                    code: 'unexpected_column',
                    object: $physicalTable.'.'.$actual->name,
                    message: sprintf(
                        'Column [%s.%s] is not part of the canonical schema.',
                        $physicalTable,
                        $actual->name,
                    ),
                );
            }
        }

        return $issues;
    }

    /**
     * @return list<SchemaIssue>
     */
    private function inspectColumn(
        ColumnDefinition $expected,
        PostgreSqlColumnMetadata $actual,
        string $object,
    ): array {
        $issues = [];

        if (! $this->hasExpectedType($expected, $actual)) {
            $issues[] = new SchemaIssue(
                code: 'column_type_mismatch',
                object: $object,
                message: sprintf(
                    'Column [%s] has PostgreSQL type [%s]; expected [%s].',
                    $object,
                    $this->describeType($actual),
                    $this->expectedType($expected),
                ),
            );
        }

        if ($actual->nullable !== $expected->nullable) {
            $issues[] = new SchemaIssue(
                code: 'column_nullability_mismatch',
                object: $object,
                message: sprintf(
                    'Column [%s] nullability does not match the canonical schema.',
                    $object,
                ),
            );
        }

        if (
            $this->isCharacterColumn($expected)
            && $actual->characterLength !== $expected->length
        ) {
            $issues[] = new SchemaIssue(
                code: 'column_length_mismatch',
                object: $object,
                message: sprintf(
                    'Column [%s] length is [%s]; expected [%d].',
                    $object,
                    $actual->characterLength === null
                        ? 'null'
                        : (string) $actual->characterLength,
                    $expected->length ?? 191,
                ),
            );
        }

        if ($expected->exactComparison && $actual->collation !== 'C') {
            $issues[] = new SchemaIssue(
                code: 'column_collation_mismatch',
                object: $object,
                message: sprintf(
                    'Column [%s] must declare the deterministic [C] collation; found [%s].',
                    $object,
                    $actual->collation ?? 'the database default',
                ),
            );
        }

        return $issues;
    }

    /**
     * @return list<SchemaIssue>
     */
    private function inspectIndexes(
        TableDefinition $table,
        string $physicalTable,
        PostgreSqlCatalogSnapshot $snapshot,
    ): array {
        $issues = [];
        $expectedNames = [];

        foreach ($table->indexes as $expected) {
            $expectedNames[] = $expected->name;
            $actual = $snapshot->index($physicalTable, $expected->name);

            if ($actual === null) {
                $issues[] = $this->missingIndex($physicalTable, $expected);

                continue;
            }

            $issues = [
                ...$issues,
                ...$this->inspectIndex($expected, $actual, $physicalTable),
            ];
        }

        $accepted = $this->acceptedConstraintIndexNames($table, $physicalTable);

        foreach ($snapshot->indexesFor($physicalTable) as $actual) {
            if (in_array($actual->name, $expectedNames, true)) {
                continue;
            }

            if (
                $actual->constraint !== null
                && in_array($actual->constraint, $accepted, true)
            ) {
                continue;
            }

            $constrains = $actual->unique || $actual->constraint !== null;

            $issues[] = new SchemaIssue(
                code: 'unexpected_index',
                object: $physicalTable.'.'.$actual->name,
                message: sprintf(
                    $constrains
                        ? 'Index [%s.%s] enforces uniqueness the canonical schema does not declare.'
                        : 'Index [%s.%s] is not part of the canonical schema.',
                    $physicalTable,
                    $actual->name,
                ),
                severity: $constrains
                    ? InspectionSeverity::Error
                    : InspectionSeverity::Warning,
            );
        }

        return $issues;
    }

    /**
     * @return list<SchemaIssue>
     */
    private function inspectIndex(
        IndexDefinition $expected,
        PostgreSqlIndexMetadata $actual,
        string $physicalTable,
    ): array {
        $object = $physicalTable.'.'.$expected->name;
        $issues = [];

        if (! $actual->complete) {
            $issues[] = new SchemaIssue(
                code: 'catalog_metadata_incomplete',
                object: $object,
                message: sprintf(
                    'Index [%s] is an expression or partial index and cannot be compared with the canonical schema.',
                    $object,
                ),
            );

            return $issues;
        }

        if (
            $actual->columns !== $expected->columns
            || $actual->unique
            || $actual->primary
            || $actual->constraint !== null
        ) {
            $issues[] = new SchemaIssue(
                code: 'index_definition_mismatch',
                object: $object,
                message: sprintf(
                    'Index [%s] does not match its canonical ordered columns or non-unique, non-constraint-backed form.',
                    $object,
                ),
            );
        }

        if (! $actual->valid || ! $actual->live) {
            $issues[] = new SchemaIssue(
                code: 'index_state_mismatch',
                object: $object,
                message: sprintf(
                    'Index [%s] is not valid and live.',
                    $object,
                ),
            );
        }

        return $issues;
    }

    /**
     * @return list<SchemaIssue>
     */
    private function inspectConstraints(
        TableDefinition $table,
        string $physicalTable,
        PostgreSqlCatalogSnapshot $snapshot,
        SchemaContext $context,
    ): array {
        $issues = [];

        foreach ($table->constraints as $expected) {
            $actual = null;

            foreach (
                $this->constraintNames($expected, $physicalTable) as $candidate
            ) {
                $actual = $snapshot->constraint($physicalTable, $candidate);

                if ($actual !== null) {
                    break;
                }
            }

            $object = $physicalTable.'.'.$expected->name;

            if ($actual === null) {
                $issues[] = new SchemaIssue(
                    code: 'missing_constraint',
                    object: $object,
                    message: sprintf(
                        'Required constraint [%s] is absent.',
                        $object,
                    ),
                );

                continue;
            }

            if ($actual->type !== $this->expectedConstraintType($expected)) {
                $issues[] = new SchemaIssue(
                    code: 'constraint_type_mismatch',
                    object: $object,
                    message: sprintf(
                        'Constraint [%s] has unexpected PostgreSQL type [%s].',
                        $object,
                        $actual->type,
                    ),
                );

                continue;
            }

            if (! $actual->validated) {
                $issues[] = new SchemaIssue(
                    code: 'constraint_state_mismatch',
                    object: $object,
                    message: sprintf(
                        'Constraint [%s] is not validated.',
                        $object,
                    ),
                );
            }

            if (
                $expected->type !== ConstraintType::Check
                && $actual->columns !== $expected->columns
            ) {
                $issues[] = new SchemaIssue(
                    code: 'constraint_columns_mismatch',
                    object: $object,
                    message: sprintf(
                        'Constraint [%s] does not use the canonical ordered columns.',
                        $object,
                    ),
                );
            }

            if ($expected->type === ConstraintType::Foreign) {
                $issues = [
                    ...$issues,
                    ...$this->inspectForeign(
                        $expected,
                        $actual,
                        $object,
                        $context,
                        $snapshot->schema,
                    ),
                ];
            }

            if ($expected->type === ConstraintType::Check) {
                $issues = [
                    ...$issues,
                    ...$this->inspectCheck($expected, $actual, $object),
                ];
            }
        }

        return $issues;
    }

    /**
     * @return list<SchemaIssue>
     */
    private function inspectForeign(
        ConstraintDefinition $expected,
        PostgreSqlConstraintMetadata $actual,
        string $object,
        SchemaContext $context,
        string $schema,
    ): array {
        $referencedTable = $expected->referencedTable === null
            ? null
            : $context->tableName($expected->referencedTable);
        $referencedSchema = $referencedTable === null ? null : $schema;
        $issues = [];

        if (
            $actual->referencedSchema !== $referencedSchema
            || $actual->referencedTable !== $referencedTable
            || $actual->referencedColumns !== $expected->referencedColumns
        ) {
            $issues[] = new SchemaIssue(
                code: 'foreign_reference_mismatch',
                object: $object,
                message: sprintf(
                    'Foreign key [%s] must reference [%s] (%s); found [%s] (%s).',
                    $object,
                    $this->qualify($referencedSchema, $referencedTable),
                    $this->columnList($expected->referencedColumns),
                    $this->qualify(
                        $actual->referencedSchema,
                        $actual->referencedTable,
                    ),
                    $this->columnList($actual->referencedColumns),
                ),
            );
        }

        if ($actual->deferrable) {
            $issues[] = new SchemaIssue(
                code: 'constraint_state_mismatch',
                object: $object,
                message: sprintf(
                    'Foreign key [%s] must be NOT DEFERRABLE; found DEFERRABLE INITIALLY %s.',
                    $object,
                    $actual->deferred ? 'DEFERRED' : 'IMMEDIATE',
                ),
            );
        }

        if ($actual->deleteRule === null || $actual->updateRule === null) {
            $issues[] = new SchemaIssue(
                code: 'catalog_metadata_incomplete',
                object: $object,
                message: sprintf(
                    'Foreign key [%s] reports a referential action PostgreSQL did not name.',
                    $object,
                ),
            );

            return $issues;
        }

        if (
            ! $this->isRestrictiveRule($actual->deleteRule)
            || ! $this->isRestrictiveRule($actual->updateRule)
        ) {
            $issues[] = new SchemaIssue(
                code: 'foreign_rule_mismatch',
                object: $object,
                message: sprintf(
                    'Foreign key [%s] must restrict delete and update operations; found ON DELETE %s ON UPDATE %s.',
                    $object,
                    $actual->deleteRule,
                    $actual->updateRule,
                ),
            );
        }

        return $issues;
    }

    /**
     * @return list<SchemaIssue>
     */
    private function inspectCheck(
        ConstraintDefinition $expected,
        PostgreSqlConstraintMetadata $actual,
        string $object,
    ): array {
        if ($actual->checkExpression === null) {
            return [
                new SchemaIssue(
                    code: 'catalog_metadata_incomplete',
                    object: $object,
                    message: sprintf(
                        'Check constraint [%s] has no readable PostgreSQL expression.',
                        $object,
                    ),
                ),
            ];
        }

        if (
            $this->normalizeCheck($actual->checkExpression)
            !== $this->normalizeCheck($expected->expression)
        ) {
            return [
                new SchemaIssue(
                    code: 'check_expression_mismatch',
                    object: $object,
                    message: sprintf(
                        'Check constraint [%s] does not match the canonical expression.',
                        $object,
                    ),
                ),
            ];
        }

        return [];
    }

    /**
     * @return list<SchemaIssue>
     */
    private function inspectGeneratedKeys(
        TableDefinition $table,
        string $physicalTable,
        PostgreSqlCatalogSnapshot $snapshot,
    ): array {
        $issues = [];

        foreach ($table->columns as $expected) {
            if ($snapshot->column($physicalTable, $expected->name) === null) {
                continue;
            }

            $object = $physicalTable.'.'.$expected->name;
            $identity = $snapshot->identity($physicalTable, $expected->name);

            if (! $expected->generated) {
                if ($identity !== null) {
                    $issues[] = new SchemaIssue(
                        code: 'generated_key_mismatch',
                        object: $object,
                        message: sprintf(
                            'Column [%s] must not generate its own value.',
                            $object,
                        ),
                    );
                }

                continue;
            }

            if ($identity === null) {
                $issues[] = new SchemaIssue(
                    code: 'generated_key_mismatch',
                    object: $object,
                    message: sprintf(
                        'Column [%s] must generate its value through an identity or sequence default.',
                        $object,
                    ),
                );

                continue;
            }

            if (! $identity->generation->acceptsExplicitValue()) {
                $issues[] = new SchemaIssue(
                    code: 'generated_key_mismatch',
                    object: $object,
                    message: sprintf(
                        'Column [%s] uses GENERATED ALWAYS identity generation, which rejects an explicitly supplied identifier.',
                        $object,
                    ),
                );
            }
        }

        return $issues;
    }

    /**
     * The constraint names a manifest constraint may legitimately carry.
     *
     * Only a primary key has more than one: Laravel's PostgreSQL grammar cannot
     * name a primary key, so package-managed provisioning leaves PostgreSQL to
     * assign `<table>_pkey`.
     *
     * @return list<string>
     */
    private function constraintNames(
        ConstraintDefinition $constraint,
        string $physicalTable,
    ): array {
        if ($constraint->type !== ConstraintType::Primary) {
            return [$constraint->name];
        }

        return [$constraint->name, $physicalTable.'_pkey'];
    }

    /**
     * Names of the primary-key and unique constraints whose backing indexes are
     * expected rather than unexpected.
     *
     * @return list<string>
     */
    private function acceptedConstraintIndexNames(
        TableDefinition $table,
        string $physicalTable,
    ): array {
        $names = [];

        foreach ($table->constraints as $constraint) {
            if (! in_array($constraint->type, [
                ConstraintType::Primary,
                ConstraintType::Unique,
            ], true)) {
                continue;
            }

            $names = [
                ...$names,
                ...$this->constraintNames($constraint, $physicalTable),
            ];
        }

        return $names;
    }

    private function hasExpectedType(
        ColumnDefinition $expected,
        PostgreSqlColumnMetadata $actual,
    ): bool {
        return match ($expected->type) {
            ColumnType::BigInteger => $actual->dataType === 'bigint',
            ColumnType::DateTime => $actual->dataType
                === 'timestamp without time zone'
                && $actual->datetimePrecision === 0,
            ColumnType::FixedString => $actual->dataType === 'character',
            ColumnType::String => $actual->dataType === 'character varying',
            ColumnType::Text => $actual->dataType === 'text',
        };
    }

    private function describeType(PostgreSqlColumnMetadata $actual): string
    {
        if (
            $actual->dataType === 'timestamp without time zone'
            && $actual->datetimePrecision !== null
        ) {
            return sprintf(
                'timestamp(%d) without time zone',
                $actual->datetimePrecision,
            );
        }

        return $actual->dataType;
    }

    private function expectedType(ColumnDefinition $expected): string
    {
        return match ($expected->type) {
            ColumnType::BigInteger => 'bigint',
            ColumnType::DateTime => 'timestamp(0) without time zone',
            ColumnType::FixedString => sprintf(
                'character(%d)',
                $expected->length ?? 1,
            ),
            ColumnType::String => sprintf(
                'character varying(%d)',
                $expected->length ?? 191,
            ),
            ColumnType::Text => 'text',
        };
    }

    private function isCharacterColumn(ColumnDefinition $expected): bool
    {
        return in_array(
            $expected->type,
            [ColumnType::FixedString, ColumnType::String],
            true,
        );
    }

    private function expectedConstraintType(
        ConstraintDefinition $constraint,
    ): string {
        return match ($constraint->type) {
            ConstraintType::Primary => 'p',
            ConstraintType::Unique => 'u',
            ConstraintType::Foreign => 'f',
            ConstraintType::Check => 'c',
        };
    }

    private function missingIndex(
        string $physicalTable,
        IndexDefinition $index,
    ): SchemaIssue {
        return new SchemaIssue(
            code: 'missing_index',
            object: $physicalTable.'.'.$index->name,
            message: sprintf(
                'Required index [%s.%s] is absent.',
                $physicalTable,
                $index->name,
            ),
        );
    }

    /**
     * `RESTRICT` and `NO ACTION` are interchangeable **only** while the
     * constraint is `NOT DEFERRABLE`, which {@see self::inspectForeign()}
     * checks separately. Neither lets a referencing row be orphaned; they
     * differ in when the check fires, and only `NO ACTION` can be postponed to
     * commit time.
     */
    private function isRestrictiveRule(string $rule): bool
    {
        return in_array(strtoupper($rule), [
            'RESTRICT',
            'NO ACTION',
        ], true);
    }

    /**
     * Renders a schema-qualified object name for a diagnostic. Only catalog
     * object names reach it — never a binding, credential or row value.
     */
    private function qualify(?string $schema, ?string $table): string
    {
        if ($table === null) {
            return 'nothing';
        }

        return $schema === null ? $table : $schema.'.'.$table;
    }

    /**
     * @param  list<string>  $columns
     */
    private function columnList(array $columns): string
    {
        return $columns === [] ? 'no columns' : implode(', ', $columns);
    }

    private function normalizeCheck(?string $expression): string
    {
        $normalized = strtolower(str_replace('"', '', (string) $expression));
        $normalized = preg_replace('/\s+/', '', $normalized) ?? $normalized;

        while ($this->hasRedundantOuterParentheses($normalized)) {
            $normalized = substr($normalized, 1, -1);
        }

        return $normalized;
    }

    private function hasRedundantOuterParentheses(string $expression): bool
    {
        if (
            strlen($expression) < 2
            || $expression[0] !== '('
            || $expression[-1] !== ')'
        ) {
            return false;
        }

        $depth = 0;
        $last = strlen($expression) - 1;

        for ($position = 0; $position <= $last; $position++) {
            if ($expression[$position] === '(') {
                $depth++;
            } elseif ($expression[$position] === ')') {
                $depth--;
            }

            if ($depth === 0 && $position < $last) {
                return false;
            }
        }

        return $depth === 0;
    }
}
